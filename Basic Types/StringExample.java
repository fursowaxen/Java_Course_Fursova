public class StringExample {
    public static void main(String[] args) {
        String s1 = "Hello" + " World";

        String s2 = "Number: " + 42;

        String s3 = "Pi = " + 3.14;

        String s4 = "Is true? " + true;

        System.out.println(s1);
        System.out.println(s2);
        System.out.println(s3);
        System.out.println(s4);
    }
}
